"""Validation driver for the neXtProt schema re-import script.

The region is a whole script: it reads "schema.ttl" and three Google-Doc
exports (TSV) from the current directory, hides the entities marked Private,
rewrites the rdfs:label / rdfs:comment of the others, and serialises the graph
after each file ("schema-tmp.N") and at the end ("schema-new.ttl").

schema.ttl is generated by the neXtProt build and is not in the repository, so
the driver stages a working directory from the fixtures next to this file:
fixture.ttl becomes schema.ttl, and goofiles_fixture/ holds the three TSV files
under their exact names (rows copied verbatim from the repository, plus one
row whose suggested label is emptied, marked in the file).  Both versions run
there, so nothing is written back into the example directory.

Oracle: module state — the `g` global of both runs by RDF isomorphism, plus
the captured stdout, which the script uses heavily (triple counts after each
removal step, "### Unknown uri", the label/comment change log).

Audit of 2026-10-31 — what the script WRITES is now compared too.  A second
run of each side, each in its own staged directory, collects the five files
it serialises (schema-tmp.0 to schema-tmp.3, schema-new.ttl): the same set of
files, each pair isomorphic, and every prefix the original's file declares
declared by the translation's (extra ones tolerated, record ldpy/027).  The
fixture also gained the empty suggestion (:Located_in, empty suggested
comment, real row; :absorptionNote, suggested label emptied): the region
removes the old value and writes nothing back.

Mutants killed (each in a copy of the pair): each of the four `-{ }` removed,
the hidden entity's subject widened, the label removal's subject coerced from
the `str`, each `len(...) > 0` guard forced True (by the empty suggestions
only) or False, the COUNT's subject widened, coerced from the `str` or its
BGP emptied, `^^xsd:string` dropped from either `+{ }`.  Equivalent, not
counted: the guard weakened to `if new_label:` (the value is always a
`str`); `@graph g` dropped for `(g)` suffixes; `@prefix rs:` for RDFS or
`@prefix xs:` for XSD -- `@graph g` binds before `g.parse(ttlfile)`, and the
parse of a schema that declares `rdfs:` and `xsd:` binds them back, so the
files serialise with the schema's own prefixes either way (checked).
"""
import contextlib
import io
import os
import shutil
import tempfile
from pathlib import Path

from rdflib import Graph

from rdfeval import harness
from rdfeval.harness import run_pair

HERE = Path(__file__).resolve().parent
WRITTEN = ["schema-tmp.0", "schema-tmp.1", "schema-tmp.2", "schema-tmp.3",
           "schema-new.ttl"]


def _stage():
    work = Path(tempfile.mkdtemp(prefix="nextprot-reimport-"))
    shutil.copy(HERE / "fixture.ttl", work / "schema.ttl")
    for tsv in (HERE / "goofiles_fixture").iterdir():
        shutil.copy(tsv, work / tsv.name)
    return work


def _written(exec_fn, path):
    """Run one side in a fresh staged directory; return what it wrote."""
    work = _stage()
    try:
        os.chdir(work)
        exec_fn(path)
        files = {}
        for name in sorted(p.name for p in work.iterdir()):
            if name.startswith("schema-"):
                g = Graph(bind_namespaces="none")
                g.parse(work / name, format="turtle")
                files[name] = g
        return files
    finally:
        os.chdir(HERE)
        shutil.rmtree(work, ignore_errors=True)


# 1. run_pair's verdict (g and stdout), kept whole; its own RDFEVAL-VERDICT
#    line is held back so that a single verdict is emitted below.
work = _stage()
os.chdir(work)
with contextlib.redirect_stderr(io.StringIO()):
    VERDICT = run_pair(str(HERE / "driver.py"), entry=None, calls=None)
os.chdir(HERE)
shutil.rmtree(work, ignore_errors=True)

# 2. the files each side writes, on a second run in its own directory.
if VERDICT.get("error") is None:
    try:
        f_o = _written(harness._exec_python, HERE / "original.py")
        f_t = _written(harness._exec_ldpy, HERE / "translated.ldpy")
        if sorted(f_o) != sorted(WRITTEN) or sorted(f_t) != sorted(f_o):
            VERDICT["diffs"].append(
                f"files written differ: {sorted(f_o)} vs {sorted(f_t)}")
        for name in sorted(set(f_o) & set(f_t)):
            go, gt = f_o[name], f_t[name]
            if not harness.graphs_isomorphic(go, gt):
                VERDICT["diffs"].append(
                    f"file {name}: not isomorphic ({len(go)} vs {len(gt)} "
                    f"triples)")
            missing = sorted({(p, str(n)) for p, n in go.namespaces()}
                             - {(p, str(n)) for p, n in gt.namespaces()})
            if missing:
                VERDICT["diffs"].append(
                    f"file {name}: prefixes of the original missing from the "
                    f"translation: {missing}")
        VERDICT["files_compared"] = sorted(set(f_o) & set(f_t))
    except Exception as e:                        # noqa: BLE001 - reported
        VERDICT["error"] = f"written files: {type(e).__name__}: {e}"
    VERDICT["equivalent"] = not VERDICT["diffs"] and VERDICT["error"] is None

harness._emit(VERDICT)
