"""Resume the draw after the analyser correction (records corpus/403, 404).

    python -m rdfeval reprise [--dry-run]

The analyser and three strata criteria were corrected on 2026-11-01, so the
population of every stratum moved: some sites left (a criterion narrowed),
many arrived (graphs the first analyser could not see). Re-drawing from
scratch would throw away every translated pair; topping up only where pairs
were lost would leave out the sites only the new analyser sees. The method
decided on 2026-11-02 (option E of record 404) does neither:

1. every FINAL pair that still has a site of the stratum stays;
2. a stratum left with fewer than ``budget`` pairs is completed to it, drawn
   from the corrected population by the rules of the original draw (seed,
   cap per repository, region unit);
3. where sites only the new analyser sees weigh at least ``min_share`` of
   the population, a few regions are drawn among them — ``per_stratum``, or
   the stratum's override — the step-2 regions that are such sites counting
   towards them;
4. every rate published per stratum is WEIGHTED: the part "seen by both
   analysers" and the part "seen by the new one only" weigh ``1 − f`` and
   ``f``, each estimated on its own regions (:func:`weighted_rate`).

Which sites the first analyser saw is read from the site index it writes
(``results/raw/sites_analyser_1.0.jsonl``), regenerated by running
``rdfeval surface`` from a checkout of commit ``822e3ef~1`` on the same
``files_index.jsonl``.

The result goes into ``strata.json`` under ``reprise`` — per stratum: the
population, the share ``f``, and the selection with each region's
sub-population and source — and the new regions are added to the draw and
materialised as drafts, like any drawn region.
"""

from __future__ import annotations

import json
import random
from collections import defaultdict

from .config import EXAMPLES_DIR, RESULTS_RAW
from .strata import (STRATA_PATH, _region_id, _source_reader,
                     region_for_site)
from .surface import SITES_RAW, STRATA

SITES_V1 = RESULTS_RAW / "sites_analyser_1.0.jsonl"

DEFAULTS = {
    "seed": 20261102,
    "budget": 25,
    "min_share": 0.15,
    "per_stratum": 5,
    "overrides": {"trav_existence": 10},
}


def _sites(path) -> list[dict]:
    rows = [json.loads(line) for line in path.read_text().splitlines()
            if line.strip()]
    return rows[1:]                       # the first row is the header


def _key(site: dict) -> tuple:
    return (site["kind"], site["repository"], site["path"], site["line"])


def _metas() -> dict[str, dict]:
    out = {}
    for path in sorted(EXAMPLES_DIR.glob("*/*/meta.json")):
        meta = json.loads(path.read_text())
        out[meta["region_id"]] = meta
    return out


def keeps_stratum(region: dict, kind: str, index: dict) -> bool:
    """Does ``region`` still hold a site of ``kind`` in the corrected index?

    A recorded site that is still a site, or any site of ``kind`` within the
    region's lines — a declaration site lies outside its region, so the
    recorded line is checked first."""
    lines = index.get((kind, region["repository"], region["path"]), set())
    if any(s["kind"] == kind and s["line"] in lines
           for s in region.get("sites", [])):
        return True
    return any(region["lineno"] <= ln <= region["end_lineno"]
               for ln in lines)


def weighted_rate(rate_both, rate_new, share_new: float):
    """A stratum's rate from its two parts (step 4).

    With no region in the new part — a stratum where ``f`` is below the
    threshold — the rate is the first part's: those sites are then too few
    to move it, and the report says ``f`` beside it."""
    if rate_new is None or share_new == 0:
        return rate_both
    if rate_both is None:
        return rate_new
    return (1 - share_new) * rate_both + share_new * rate_new


def plan(sites_new: list[dict], sites_v1: list[dict], draw: dict,
         metas: dict, scfg: dict, rcfg: dict, rp: dict, eligible: set,
         source_of) -> dict:
    """The resumed selection, stratum by stratum (steps 1 to 3)."""
    seen_v1 = {_key(s) for s in sites_v1}
    index = defaultdict(set)
    for s in sites_new:
        index[(s["kind"], s["repository"], s["path"])].add(s["line"])
    regions = draw["regions"]
    rng = random.Random(rp["seed"])
    cap = scfg["max_per_repo_per_stratum"]
    added: dict[str, dict] = {}
    out: dict[str, dict] = {}
    for kind in sorted(STRATA):
        if kind == "trav_on_dataset":
            continue                      # measured, never drawn
        pool = sorted((s for s in sites_new
                       if s["kind"] == kind and s["repository"] in eligible),
                      key=lambda s: (s["repository"], s["path"], s["line"]))
        new_only = [s for s in pool if _key(s) not in seen_v1]
        share = len(new_only) / len(pool) if pool else 0.0
        selection = []
        per_repo: dict[str, int] = defaultdict(int)
        # step 1 — the finals that keep the stratum
        for rid, meta in sorted(metas.items()):
            if meta.get("translation_status") != "final" \
                    or kind not in meta.get("strata", []) \
                    or rid not in regions:
                continue
            region = regions[rid]
            if keeps_stratum(region, kind, index):
                selection.append({"region_id": rid, "subpop": "both",
                                  "source": "final"})
                per_repo[region["repository"]] += 1
        taken = {e["region_id"] for e in selection}

        def draw_from(sites, n, subpop_of, source):
            got = 0
            order = list(range(len(sites)))
            rng.shuffle(order)
            for i in order:
                if got >= n:
                    break
                site = sites[i]
                if per_repo[site["repository"]] >= cap:
                    continue
                text = source_of(site["repository"], site["path"])
                if text is None:
                    continue
                region = region_for_site(text, site["line"], rcfg)
                if region is None:
                    continue
                rid = _region_id(site["repository"], site["path"],
                                 region["qualname"], region["lineno"])
                if rid in taken:
                    continue
                meta = metas.get(rid)
                if meta and meta.get("classification") in (
                        "excluded", "not-expressible") \
                        and meta.get("translation_status") != "final":
                    continue
                taken.add(rid)
                per_repo[site["repository"]] += 1
                if rid not in regions:
                    record = added.setdefault(rid, {
                        **region, "region_id": rid,
                        "repository": site["repository"],
                        "path": site["path"], "commit": site.get("commit"),
                        "strata": [], "sites": []})
                    if kind not in record["strata"]:
                        record["strata"].append(kind)
                    record["sites"].append({"kind": kind,
                                            "line": site["line"],
                                            "end_line": site["end_line"]})
                selection.append({"region_id": rid,
                                  "subpop": subpop_of(site),
                                  "source": source})
                got += 1
            return got

        # step 2 — complete to the budget, from the whole corrected pool
        need = max(0, rp["budget"] - len(selection))
        draw_from(pool, need,
                  lambda s: "new" if _key(s) not in seen_v1 else "both",
                  "completed")
        # step 3 — the sites only the new analyser sees
        if share >= rp["min_share"]:
            want = rp["overrides"].get(kind, rp["per_stratum"])
            have = sum(1 for e in selection if e["subpop"] == "new")
            draw_from(new_only, max(0, want - have), lambda s: "new",
                      "new-only")
        out[kind] = {
            "population_sites": len(pool),
            "population_new_only": len(new_only),
            "share_new": round(share, 4),
            "selection": selection,
        }
    return {"strata": out, "added": added}


def run(config: dict, dry_run: bool = False) -> dict:
    from .select import load_manifest

    rp = {**DEFAULTS, **config.get("reprise", {})}
    if not SITES_V1.exists():
        raise SystemExit(f"{SITES_V1} is missing: run `rdfeval surface` "
                         "from a checkout of 822e3ef~1 (see this module)")
    draw = json.loads(STRATA_PATH.read_text())
    eligible = {m["full_name"] for m in load_manifest()
                if m.get("snippet_ok") and not m.get("pruned")}
    result = plan(_sites(SITES_RAW), _sites(SITES_V1), draw, _metas(),
                  config["strata"], config["regions"], rp, eligible,
                  _source_reader(config))
    for kind, st in result["strata"].items():
        sel = st["selection"]
        count = defaultdict(int)
        for e in sel:
            count[e["source"]] += 1
        print(f"  {kind:24s} f={st['share_new']:.2f}  "
              f"finals {count['final']:3d}  completed {count['completed']:2d}"
              f"  new-only {count['new-only']:2d}  "
              f"(new part: {sum(e['subpop'] == 'new' for e in sel)})")
    metas = _metas()
    selected = {e["region_id"] for st in result["strata"].values()
                for e in st["selection"]}
    todo = sorted(r for r in selected
                  if metas.get(r, {}).get("translation_status") != "final")
    print(f"reprise: {len(selected)} regions selected, {len(todo)} to "
          f"translate ({len(result['added'])} new to the draw)")
    result["to_translate"] = todo
    if dry_run:
        return result
    for rid, record in result["added"].items():
        draw["regions"][rid] = record
    for kind, st in result["strata"].items():
        for e in st["selection"]:
            reg = draw["regions"][e["region_id"]]
            if kind not in reg["strata"]:
                reg["strata"].append(kind)
    draw["reprise"] = {"method": "record corpus/404, option E (2026-11-02)",
                       "parameters": rp, "strata": result["strata"]}
    STRATA_PATH.write_text(json.dumps(draw, indent=2, ensure_ascii=False),
                           encoding="utf-8")
    print("translate:", materialise_selected(config, draw, todo))
    return result


def materialise_selected(config: dict, draw: dict, region_ids) -> dict:
    """Drafts for the selected regions that have no directory yet — never
    :func:`rdfeval.strata.materialise_all`, which would bring back every
    region of the draw left out of the sample, and redraft the drafts whose
    notes say why they were left."""
    from .translate import materialise
    counts: dict[str, int] = {}
    for rid in region_ids:
        reg = dict(draw["regions"][rid])
        reg["stratum"] = reg["strata"][0]
        if (EXAMPLES_DIR / reg["stratum"] / rid).exists():
            counts["exists"] = counts.get("exists", 0) + 1
            continue
        status = materialise(reg, config, root=EXAMPLES_DIR, group="stratum")
        counts[status] = counts.get(status, 0) + 1
        review = EXAMPLES_DIR / reg["stratum"] / rid / "review.json"
        if not review.exists():
            review.write_text(json.dumps({
                "region_id": rid, "review_status": "unreviewed",
                "reviewer": None, "reviewed_at": None, "comment": None,
            }, indent=2, ensure_ascii=False), encoding="utf-8")
    return counts
